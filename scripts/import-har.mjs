#!/usr/bin/env node
/**
 * Turns a browser network export (HAR) from staging into demo recordings.
 *
 *   node scripts/import-har.mjs <file.har> <name> [--map <stagingId>=<demoId> ...]
 *
 * 1. On staging, sign in to the demo company and open DevTools → Network.
 * 2. Click through the screens you want in the demo.
 * 3. Right-click the request list → "Save all as HAR (sanitized)".
 * 4. Run this script. It writes demo/fixtures/recorded/<name>.json and
 *    regenerates demo/fixtures/recorded/index.ts.
 *
 * What it does to the data:
 * - keeps successful JSON responses from /api/v1 (the last response wins per request);
 * - replaces ids passed with --map everywhere (paths, queries, bodies). Map the
 *   staging company and user ids to the demo ones in demo/data/tenant.ts, or the
 *   recordings won't line up with the rest of the demo;
 * - drops `company_id` and cache-busting params from query matching;
 * - replaces signed URLs (S3/GCS signatures) with a placeholder;
 * - lists every email address it finds, so you can check no real person's
 *   details are in the recording before committing it.
 *
 * Only record from a made-up demo company. Never from a real tenant.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = path.join(ROOT, "demo", "fixtures", "recorded");
const IGNORED_QUERY = new Set(["company_id", "_", "_t", "t", "timestamp", "cb"]);
const SIGNED_URL = /https?:\/\/[^\s"']+[?&](X-Amz-Signature|X-Goog-Signature|Signature)=[^\s"']+/g;
const EMAIL = /[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g;

function usage(message) {
  if (message) console.error(`error: ${message}\n`);
  console.error("usage: node scripts/import-har.mjs <file.har> <name> [--map <stagingId>=<demoId> ...]");
  process.exit(1);
}

const args = process.argv.slice(2);
const positional = [];
const idMap = [];
for (let i = 0; i < args.length; i++) {
  if (args[i] === "--map") {
    const [from, to] = String(args[++i] ?? "").split("=");
    if (!from || !to) usage("--map needs <stagingId>=<demoId>");
    idMap.push([from, to]);
  } else {
    positional.push(args[i]);
  }
}
const [harFile, name] = positional;
if (!harFile || !name) usage();
if (!/^[a-z0-9-]+$/.test(name)) usage("name must be lower-case letters, digits and dashes");

const replaceIds = (text) => idMap.reduce((acc, [from, to]) => acc.split(from).join(to), text);

const har = JSON.parse(fs.readFileSync(harFile, "utf8"));
const byKey = new Map();
const emails = new Set();
let signedUrls = 0;
let skipped = 0;

for (const entry of har.log?.entries ?? []) {
  const { request, response } = entry;
  const url = new URL(request.url);
  const apiIndex = url.pathname.indexOf("/api/v1/");
  const content = response?.content ?? {};
  const isJson = String(content.mimeType ?? "").includes("json");
  if (apiIndex === -1 || !isJson || response.status < 200 || response.status >= 300 || content.text == null) {
    skipped += 1;
    continue;
  }

  let text = content.encoding === "base64" ? Buffer.from(content.text, "base64").toString("utf8") : content.text;
  text = replaceIds(text).replace(SIGNED_URL, () => {
    signedUrls += 1;
    return "/demo-docs/placeholder.pdf";
  });
  for (const match of text.match(EMAIL) ?? []) emails.add(match);

  let data;
  try {
    data = JSON.parse(text);
  } catch {
    skipped += 1;
    continue;
  }

  const apiPath = replaceIds(url.pathname.slice(apiIndex + "/api/v1".length)).replace(/\/+$/, "") || "/";
  const query = {};
  for (const [key, value] of url.searchParams) {
    if (!IGNORED_QUERY.has(key)) query[key] = replaceIds(value);
  }
  const method = request.method.toUpperCase();
  const key = `${method} ${apiPath} ${JSON.stringify(query)}`;
  byKey.set(key, {
    method,
    path: apiPath,
    ...(Object.keys(query).length ? { query } : {}),
    status: response.status,
    data,
  });
}

const entries = [...byKey.values()].sort((a, b) => `${a.path} ${a.method}`.localeCompare(`${b.path} ${b.method}`));
fs.mkdirSync(OUT_DIR, { recursive: true });
fs.writeFileSync(path.join(OUT_DIR, `${name}.json`), `${JSON.stringify(entries, null, 2)}\n`);

// Regenerate the index from every recording on disk.
const files = fs.readdirSync(OUT_DIR).filter((f) => f.endsWith(".json")).sort();
const ident = (file) => `rec_${file.replace(/\.json$/, "").replace(/[^a-zA-Z0-9]/g, "_")}`;
fs.writeFileSync(
  path.join(OUT_DIR, "index.ts"),
  [
    "// Recorded staging responses, replayed by demo/server/recorded.ts.",
    "// Generated by scripts/import-har.mjs — do not edit by hand.",
    'import type { RecordedEntry } from "@/demo/server/recorded";',
    ...files.map((f) => `import ${ident(f)} from "./${f}";`),
    "",
    `export const recordings: RecordedEntry[] = [${files.map((f) => `\n  ...(${ident(f)} as RecordedEntry[]),`).join("")}${files.length ? "\n" : ""}];`,
    "",
  ].join("\n")
);

console.log(`Wrote ${entries.length} responses to demo/fixtures/recorded/${name}.json (skipped ${skipped} non-API or failed requests).`);
for (const e of entries) console.log(`  ${e.method.padEnd(6)} ${e.path}${e.query ? ` ${JSON.stringify(e.query)}` : ""}`);
if (signedUrls) console.log(`\nReplaced ${signedUrls} signed URL(s) with /demo-docs/placeholder.pdf.`);
if (emails.size) {
  console.log("\nEmail addresses in the recording. Check none belongs to a real person before committing:");
  for (const email of [...emails].sort()) console.log(`  ${email}`);
}
if (!idMap.length) {
  console.log("\nNo --map given: ids are staging ids. Map the staging company/user ids to demo/data/tenant.ts.");
}
